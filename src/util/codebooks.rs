/// Index of the value in a sorted (ascending, no NaN) codebook nearest to `z`.
pub fn nearest(codebook: &[f32], z: f32) -> usize {
    match codebook.binary_search_by(|c| c.partial_cmp(&z).unwrap()) {
        Ok(i) => i,
        Err(0) => 0,
        Err(i) if i >= codebook.len() => codebook.len() - 1,
        Err(i) => {
            if (z - codebook[i - 1]).abs() <= (codebook[i] - z).abs() {
                i - 1
            } else {
                i
            }
        }
    }
}

/// Lloyd–Max optimal `n`-level scalar quantizer for `N(0,1)`, as sorted
/// centroids read from the fixed [`NORMAL_LLOYD_MAX`] table (not recomputed from
/// data). `n` must be `1` (the mean) or a power of two in `2..=256`.
pub fn lloyd_max_normal(n: usize) -> Vec<f32> {
    assert!(n >= 1);
    if n == 1 {
        return vec![0.0]; // the optimal single level is the mean of N(0,1)
    }
    assert!(
        n.is_power_of_two() && n <= 256,
        "lloyd_max_normal: n must be a power of two in 1..=256, got {n}"
    );
    let b = n.trailing_zeros() as usize; // tabulated bit-depth (2^b == n)
    NORMAL_LLOYD_MAX[b - 1].to_vec()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rows_have_pow2_arity_and_are_sorted() {
        for (i, row) in NORMAL_LLOYD_MAX.iter().enumerate() {
            assert_eq!(row.len(), 1 << (i + 1), "b={} arity", i + 1);
            assert!(
                row.windows(2).all(|w| w[0] < w[1]),
                "b={} not sorted",
                i + 1
            );
        }
    }

    #[test]
    fn one_level_is_the_mean() {
        assert!((lloyd_max_normal(1)[0]).abs() < 1e-3);
    }

    #[test]
    fn two_levels_match_half_normal_mean() {
        // Optimal 1-bit quantizer for N(0,1) sits at ±E[|N|] = ±√(2/π) ≈ ±0.7979.
        let c = lloyd_max_normal(2);
        let want = (2.0f32 / std::f32::consts::PI).sqrt();
        assert!((c[0] + want).abs() < 1e-2, "{}", c[0]);
        assert!((c[1] - want).abs() < 1e-2, "{}", c[1]);
    }

    #[test]
    fn matches_quant_arena_table_b4() {
        // Fixed Lloyd-Max N(0,1) levels for B=4 from quant-arena/codebooks/normal_lloyd_max.txt
        let table: [f32; 16] = [
            -2.73258958,
            -2.06901724,
            -1.61804640,
            -1.25623121,
            -0.94234046,
            -0.65675912,
            -0.38804830,
            -0.12839503,
            0.12839503,
            0.38804830,
            0.65675912,
            0.94234046,
            1.25623121,
            1.61804640,
            2.06901724,
            2.73258958,
        ];
        let c = lloyd_max_normal(16);
        for (a, b) in c.iter().zip(&table) {
            assert!((a - b).abs() < 1e-6, "{a} vs table {b}");
        }
    }

    #[test]
    fn sorted_and_symmetric() {
        let c = lloyd_max_normal(8);
        assert!(c.windows(2).all(|w| w[0] < w[1]), "not sorted: {c:?}");
        // symmetric about 0
        for (a, b) in c.iter().zip(c.iter().rev()) {
            assert!((a + b).abs() < 1e-2, "asymmetric {a} vs {b}");
        }
    }
}
